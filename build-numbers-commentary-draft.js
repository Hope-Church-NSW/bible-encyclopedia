const drafts = {};
for (const verse of chapter) {
  const key = `1:${verse.verse}`;
  const bibleKey = `04-Numbers:${key}`;
  const summary = summaries[verse.verse];
  const indexed = sourceIndex[key];
  if (!summary || !indexed) throw new Error(`Missing draft or source index for Numbers ${key}`);
  drafts[key] = {
    reference: `العدد ${key}`,
    text: verse.text,
    summary,
    sources: Object.entries(indexed.sources).map(([id, records]) => ({
      id,
      locators: records.map(record => record.locator),
      ranges: records.map(record => record.range)
    })),
    interpreter_names: Object.keys(indexed.sources).map(id => interpreterNames[id] || id),
    supplemental_sources: (supportIndex.verses[bibleKey] || [])
      .filter(link => link.scope === 'verse_or_passage')
      .sort((left, right) => {
        const priority = { direct: 0, geography: 1, character: 2, messianic: 3, background: 4, encyclopedia: 5 };
        return (priority[left.relation] ?? 9) - (priority[right.relation] ?? 9);
      })
      .slice(0, 6)
      .map(link => ({
        record_id: link.record_id,
        relation: link.relation,
        title: supportIndex.records[link.record_id].title,
        source_file: supportIndex.records[link.record_id].source_file
      })),
    status: 'research_draft'
  };
}

const normalized = Object.values(drafts).map(entry => entry.summary.replace(/[\s\p{P}]+/gu, ' ').trim());
const duplicateCount = normalized.length - new Set(normalized).size;
const problems = [];
if (chapter.length !== 54 || Object.keys(drafts).length !== 54) problems.push('Expected 54 verses');
if (duplicateCount) problems.push(`${duplicateCount} duplicate summaries`);
for (const [key, entry] of Object.entries(drafts)) {
  if (entry.summary.length < 100) problems.push(`${key}: summary is too short`);
  if (!entry.sources.length) problems.push(`${key}: no indexed source`);
  if (entry.sources.some(source => !source.locators.length || source.locators.some(locator => !locator))) {
    problems.push(`${key}: missing source locator`);
  }
  if (/الأصل اللغوي|العبرية|اليونانية/.test(entry.summary)) problems.push(`${key}: unreviewed language claim`);
}
if (problems.length) throw new Error(problems.join('\n'));

const output = {
  book: '04-Numbers',
  chapter: 1,
  status: 'research_draft',
  generated_from: 'sources/commentaries/numbers/source-index.json',
  verses: drafts
};
fs.writeFileSync(path.join(sourceDir, 'draft-chapter-01.json'), `${JSON.stringify(output, null, 2)}\n`, 'utf8');
console.log(`Numbers 1 draft validated: ${Object.keys(drafts).length} unique verse summaries`);