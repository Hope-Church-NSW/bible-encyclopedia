export function getSydneyDateParts(date = new Date()) {
  const parts = new Intl.DateTimeFormat('en-AU', {
    timeZone: 'Australia/Sydney',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23'
  }).formatToParts(date);
  return Object.fromEntries(parts.filter((part) => part.type !== 'literal').map(({ type, value }) => [type, Number(value)]));
}

export function getDailyVerseForDate(date = new Date()) {
  const { year, month, day } = getSydneyDateParts(date);
  const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
  return DAILY_VERSES[((dayNumber % DAILY_VERSES.length) + DAILY_VERSES.length) % DAILY_VERSES.length];
}
